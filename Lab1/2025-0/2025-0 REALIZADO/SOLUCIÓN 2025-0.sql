CREATE TABLE L3_HISTORICO_PRECIOS(
    HISTORICO_ID    NUMBER NOT NULL,
    PRODUCTO_ID     NUMBER NOT NULL,
    PRECIO_ANTERIOR NUMBER(10,2) NOT NULL,
    PRECIO_NUEVO    NUMBER(10,2) NOT NULL,
    FECHA_INICIO_VIGENCIA DATE NOT NULL,
    FECHA_FIN_VIGENCIA    DATE NOT NULL,
    MOTIVO_CAMBIO   VARCHAR2(100) NOT NULL,
    USUARIO_REGISTRO VARCHAR2(100) NOT NULL,
    FECHA_REGISTRO DATE DEFAULT SYSDATE,
    CONSTRAINT PK_HISTORICO_PRECIOS PRIMARY KEY (HISTORICO_ID),
    CONSTRAINT FK_HISTORICO_PRODUCTOS FOREIGN KEY (PRODUCTO_ID)
    REFERENCES L3_PRODUCTOS(PRODUCTO_ID)
);

