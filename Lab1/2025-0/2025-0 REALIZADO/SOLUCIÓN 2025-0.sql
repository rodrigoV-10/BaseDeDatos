SELECT
P.CODIGO_PRODUCTO,
P.NOMBRE AS NOMBRE_LIBRO,
L.ISBN,
E.NOMBRE AS EDITORIAL,
E.PAIS_ORIGEN,
E.CONTACTO_NOMBRE
FROM L3_PRODUCTOS P, L3_LIBROS L,L3_EDITORIALES E
WHERE P.PRODUCTO_ID = L.PRODUCTO_ID
AND P.EDITORIAL_ID = E.EDITORIAL_ID
AND P.ESTADO = 'ACTIVO'
AND P.PRECIO_BASE > 100
ORDER BY P.NOMBRE;

