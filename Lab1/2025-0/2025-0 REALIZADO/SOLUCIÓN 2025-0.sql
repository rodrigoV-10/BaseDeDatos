SELECT PE.PEDIDO_ESPECIAL_ID,
PE.FECHA_SOLICITUD,
PE.ESTADO,
C.NOMBRE||' '|| C.APELLIDO AS NOMBRE_COMPLETO,
C.EMAIL,
C.TELEFONO
FROM L3_PEDIDOS_ESPECIALES PE, L3_CLIENTES C
WHERE C.CLIENTE_ID = PE.CLIENTE_ID
AND TO_CHAR(PE.FECHA_SOLICITUD,'YYYY') = '2024'
AND PE.MONTO_ADELANTADO >200
ORDER BY PE.FECHA_SOLICITUD;

